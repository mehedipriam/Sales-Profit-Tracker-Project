package com.salestracker.agent;

import com.salestracker.agent.Intent.ExpenseDetails;
import com.salestracker.agent.LedgerReplies.ExpenseCard;
import com.salestracker.auth.AuthUser;
import com.salestracker.common.DateRange;
import com.salestracker.customer.CustomerRepository;
import com.salestracker.expense.ExpenseDtos.ExpenseRequest;
import com.salestracker.expense.ExpenseDtos.ExpenseResponse;
import com.salestracker.expense.ExpenseService;
import com.salestracker.order.SaleOrder;
import org.springframework.security.access.prepost.PreAuthorize;
import org.springframework.stereotype.Service;
import org.springframework.transaction.annotation.Transactional;

import java.math.BigDecimal;
import java.time.LocalDate;
import java.util.ArrayList;
import java.util.List;
import java.util.Optional;

/**
 * Recording an expense from the chat: Owner and Admin only, like the Expenses page. The message only prepares a card;
 * Confirm saves it through the same rules as the Expenses page.
 */
@Service
public class ExpenseAssistant {
    private static final BigDecimal MAX = new BigDecimal("9999999999.99");

    private final ExpenseService expenses;
    private final OrderLookup lookup;
    private final CustomerRepository customers;
    private final QuestionService questions;

    public ExpenseAssistant(ExpenseService expenses, OrderLookup lookup, CustomerRepository customers, QuestionService questions) {
        this.expenses = expenses;
        this.lookup = lookup;
        this.customers = customers;
        this.questions = questions;
    }

    @Transactional(readOnly = true)
    public AgentReply handle(AuthUser user, Intent in) {
        if (!user.role().seesFinancials()) {
            return AgentReply.message("Expenses are for the Owner and Admin only, like the Expenses page.");
        }
        ExpenseDetails e = in.expense();
        if (e == null || e.type() == null) {
            return AgentReply.message("What kind of expense is it: delivery, packaging, ads, platform commission or other?");
        }
        if (e.amount() == null || e.amount().signum() <= 0) {
            return AgentReply.message("How much was it? The amount must be above zero.");
        }
        if (e.amount().scale() > 2 || e.amount().compareTo(MAX) > 0) {
            return AgentReply.message("That amount is not valid. Use at most two decimals.");
        }
        Long tenant = user.tenantId();
        LocalDate date = e.date() != null ? e.date() : questions.today();

        Long orderId = null;
        String orderNo = null;
        String customerName = null;
        if (e.orderRef() != null && !e.orderRef().isBlank()) {
            Optional<SaleOrder> order = lookup.byNumber(tenant, e.orderRef().trim());
            if (order.isEmpty()) return AgentReply.message("No order matches \"" + e.orderRef().trim() + "\". Nothing was recorded.");
            orderId = order.get().getId();
            orderNo = order.get().getOrderNo();
            customerName = customers.findById(order.get().getCustomerId()).map(c -> c.getName()).orElse(null);
        }

        List<String> warnings = new ArrayList<>();
        String description = e.description() == null || e.description().isBlank() ? null : e.description().trim();
        boolean same = expenses.list(tenant, e.type(), orderId, DateRange.of(date, date), 0, 20).content().stream()
                .anyMatch(x -> !x.autoGenerated() && x.amount().compareTo(e.amount()) == 0);
        if (same) warnings.add("An expense of the same type and amount is already recorded for " + date + ". Check this is not a duplicate");
        return AgentReply.expense(new ExpenseCard(e.type(), e.amount(), date, description, orderId, orderNo, customerName, warnings));
    }

    /** Confirm: saved exactly like an expense typed on the Expenses page. */
    @PreAuthorize("hasAnyRole('OWNER','ADMIN')")
    public ExpenseResponse confirm(AuthUser user, ExpenseRequest req) {
        return expenses.create(user.tenantId(), req);
    }
}
