package com.salestracker.courier;

import com.fasterxml.jackson.databind.JsonNode;
import com.salestracker.AbstractIntegrationTest;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;

import java.math.BigDecimal;

import static org.junit.jupiter.api.Assertions.*;

/**
 * A courier keeps its delivery fee and a COD percentage of what is left out of the cash it collects: with Steadfast's
 * 75 inside Dhaka and 1% COD, a 1,610 parcel pays the business 1,520 and costs it 90 in charges.
 */
class CourierChargesIntegrationTest extends AbstractIntegrationTest {

    private Tenant tenant;
    private long facebook;
    private long customer;
    private long steadfast;
    private long product; // cost 1230, sold at 1500

    @BeforeEach
    void setUp() throws Exception {
        tenant = registerTenant();
        facebook = get(tenant, "/api/platforms", 200).get(0).get("id").asLong();
        customer = post(tenant, "/api/customers", "{\"name\":\"Al Mamun\"}", 201).get("id").asLong();
        product = post(tenant, "/api/products", "{\"name\":\"Cow\",\"costPrice\":1230,\"sellingPrice\":1500}", 201).get("id").asLong();
        for (JsonNode c : get(tenant, "/api/couriers", 200)) {
            if (c.get("name").asText().equals("Steadfast")) steadfast = c.get("id").asLong();
        }
        put(tenant, "/api/couriers/" + steadfast, "{\"name\":\"Steadfast\",\"feeInside\":75,\"feeOutside\":130}", 200);
    }

    private JsonNode order(String status, String zone, String codAmount) throws Exception {
        return post(tenant, "/api/orders", """
                {"platformId":%d,"customerId":%d,"status":"%s","deliveryCharge":110,"courierId":%d,
                 "deliveryZone":"%s","codAmount":%s,
                 "items":[{"productId":%d,"quantity":1,"soldPrice":1500}]}
                """.formatted(facebook, customer, status, steadfast, zone, codAmount, product), 201);
    }

    private static void assertMoney(String expected, JsonNode actual) {
        assertEquals(0, new BigDecimal(expected).compareTo(actual.decimalValue()), "expected " + expected + " but was " + actual);
    }

    private JsonNode autoDelivery(JsonNode order) {
        for (JsonNode e : order.get("expenses")) {
            if (e.get("autoGenerated").asBoolean() && e.get("type").asText().equals("DELIVERY")) return e;
        }
        return null;
    }

    @Test
    void steadfastsCodChargeIsOnePercentAfterItsDeliveryFee() throws Exception {
        assertMoney("1", get(tenant, "/api/couriers", 200).findValuesAsText("name").contains("Steadfast")
                ? get(tenant, "/api/couriers", 200).get(3).get("codPct") : null);

        JsonNode o = order("PENDING", "INSIDE", "null");
        JsonNode courier = o.get("courier");
        assertMoney("1610", courier.get("codAmount"));
        assertMoney("75", courier.get("deliveryFee"));
        assertMoney("15", courier.get("codFee")); // 1% of 1,535
        assertMoney("1520", courier.get("youReceive"));
        assertMoney("90", autoDelivery(o).get("amount"));

        // The customer paid 110 for delivery, the courier took 90: 20 is left over.
        long id = o.get("id").asLong();
        patch(tenant, "/api/orders/" + id + "/status", "{\"status\":\"PAID\"}", 200);
        JsonNode summary = get(tenant, "/api/reports/summary", 200);
        assertMoney("290", summary.get("netProfit")); // 270 gross + 110 delivery - 90 courier
        assertMoney("20", summary.get("courierDeliveryProfit")); // 110 charged - 90 kept by the courier

        // What the courier owes is what reaches the business, not the whole cash collected.
        assertMoney("1520", get(tenant, "/api/couriers/payouts", 200).get("dueTotal"));
    }

    @Test
    void outsideDhakaUsesTheOtherFeeAndTheChargeIsRoundedToTheNearestTaka() throws Exception {
        JsonNode outside = order("PENDING", "OUTSIDE", "null").get("courier");
        assertMoney("130", outside.get("deliveryFee"));
        assertMoney("15", outside.get("codFee")); // 1% of 1,480 is 14.80

        put(tenant, "/api/couriers/" + steadfast, "{\"name\":\"Steadfast\",\"feeInside\":0}", 200);
        assertMoney("5", order("PENDING", "INSIDE", "549").get("courier").get("codFee")); // 5.49
        assertMoney("6", order("PENDING", "INSIDE", "550").get("courier").get("codFee")); // 5.50
    }

    @Test
    void aReturnedOrderGivesTheChargesBackAndOldOrdersKeepTheirCharges() throws Exception {
        JsonNode o = order("PENDING", "INSIDE", "null");
        long id = o.get("id").asLong();

        // Changing the courier's rates later does not rewrite an order that is already saved.
        put(tenant, "/api/couriers/" + steadfast, "{\"name\":\"Steadfast\",\"feeInside\":99}", 200);
        assertMoney("75", get(tenant, "/api/orders/" + id, 200).get("courier").get("deliveryFee"));

        JsonNode returned = patch(tenant, "/api/orders/" + id + "/status", "{\"status\":\"RETURNED\"}", 200);
        assertNull(autoDelivery(returned));
    }

    @Test
    void aDeliveryFeeTypedOnTheOrderReplacesTheCouriersUsualFee() throws Exception {
        JsonNode created = post(tenant, "/api/orders", """
                {"platformId":%d,"customerId":%d,"status":"PENDING","deliveryCharge":110,"courierId":%d,"courierFee":80,
                 "items":[{"productId":%d,"quantity":1,"soldPrice":1500}]}
                """.formatted(facebook, customer, steadfast, product), 201);
        JsonNode courier = created.get("courier");
        assertMoney("80", courier.get("deliveryFee"));
        assertMoney("15", courier.get("codFee")); // 1% of 1,530 is 15.30
        assertMoney("1515", courier.get("youReceive"));
        assertMoney("95", autoDelivery(created).get("amount"));

        // Without a fee on the order the courier's usual 75 is used.
        assertMoney("75", order("PENDING", "INSIDE", "null").get("courier").get("deliveryFee"));
    }

    @Test
    void theOrderListProfitIncludesWhatDeliveryEarnsAfterTheCourierTakesItsShare() throws Exception {
        JsonNode created = order("PENDING", "INSIDE", "null");
        JsonNode row = get(tenant, "/api/orders", 200).get("content").get(0);
        // 270 on the product, plus the 110 the customer paid for delivery, less the 90 the courier kept.
        assertMoney("290", row.get("profit"));
        // The order's own product profit is unchanged.
        assertMoney("270", get(tenant, "/api/orders/" + created.get("id").asLong(), 200).get("profit"));
    }

    @Test
    void anOrderWithoutACourierKeepsItsProductProfitInTheList() throws Exception {
        post(tenant, "/api/orders", """
                {"platformId":%d,"customerId":%d,"status":"PAID","deliveryCharge":110,
                 "items":[{"productId":%d,"quantity":1,"soldPrice":1500}]}
                """.formatted(facebook, customer, product), 201);
        // The cost of delivering it is not known here, so the 110 the customer paid is not counted as profit.
        assertMoney("270", get(tenant, "/api/orders", 200).get("content").get(0).get("profit"));
    }

    @Test
    void anEarningTypedOnTheOrderReplacesTheCouriersRates() throws Exception {
        JsonNode created = post(tenant, "/api/orders", """
                {"platformId":%d,"customerId":%d,"status":"PENDING","deliveryCharge":110,"courierId":%d,"courierEarning":20,
                 "items":[{"productId":%d,"quantity":1,"soldPrice":1500}]}
                """.formatted(facebook, customer, steadfast, product), 201);
        JsonNode courier = created.get("courier");
        assertMoney("20", courier.get("earning"));
        assertMoney("90", courier.get("deliveryFee")); // the courier keeps the rest of the 110
        assertMoney("0", courier.get("codFee"));
        assertMoney("1520", courier.get("youReceive"));
        assertMoney("90", autoDelivery(created).get("amount"));
        assertMoney("290", get(tenant, "/api/orders", 200).get("content").get(0).get("profit")); // 270 + 20

        // Edited without it, the order goes back to the courier's rates.
        long id = created.get("id").asLong();
        JsonNode back = put(tenant, "/api/orders/" + id, """
                {"platformId":%d,"customerId":%d,"status":"PENDING","deliveryCharge":110,"courierId":%d,
                 "items":[{"productId":%d,"quantity":1,"soldPrice":1500}]}
                """.formatted(facebook, customer, steadfast, product), 200).get("courier");
        assertTrue(back.get("earning").isNull());
        assertMoney("75", back.get("deliveryFee"));
    }

    @Test
    void aParcelPaidInAdvanceStillPaysTheDeliveryFeeButNoCodCharge() throws Exception {
        JsonNode courier = order("PENDING", "INSIDE", "0").get("courier");
        assertMoney("75", courier.get("deliveryFee"));
        assertMoney("0", courier.get("codFee"));
    }
}
